static const uint8_t unknown[5] = {0x02,0x01,0x51,0x09,0x06};

const uint8_t *font_glyph(uint32_t codepoint) {
    if (codepoint >= 'a' && codepoint <= 'z') codepoint -= 'a' - 'A';
    if (codepoint >= 0x0430 && codepoint <= 0x044f) codepoint -= 0x20;
    if (codepoint == 0x0451) codepoint = 0x0401;
    if (codepoint == 0x0456) codepoint = 0x0406;
    if (codepoint == 0x045e) codepoint = 0x040e;
    for (size_t i = 0; i < sizeof(glyphs) / sizeof(glyphs[0]); ++i)
        if (glyphs[i].cp == codepoint) return glyphs[i].bits;
    return unknown;
}
