static uint8_t order[FORTUNE_COUNT];
static size_t next_index;
static const char *last_fortune;

void fortunes_shuffle(void) {
    for (size_t i = 0; i < FORTUNE_COUNT; ++i) order[i] = (uint8_t)i;
    for (size_t i = FORTUNE_COUNT - 1; i > 0; --i) {
        const size_t j = get_rand_32() % (i + 1);
        const uint8_t temp = order[i]; order[i] = order[j]; order[j] = temp;
    }
    if (last_fortune && fortune_list[order[0]] == last_fortune) {
        const uint8_t temp = order[0]; order[0] = order[1]; order[1] = temp;
    }
    next_index = 0;
}

const char *fortunes_next(void) {
    if (next_index == FORTUNE_COUNT) fortunes_shuffle();
    last_fortune = fortune_list[order[next_index++]];
    return last_fortune;
}

size_t fortunes_positive_count(void) { return 96; }
size_t fortunes_negative_count(void) { return 24; }
